def _alt(*groups):
    """幾組字表合成「a|b|c」（去重、保留順序、長字在前避免短字先吃掉）。"""
    seen = []
    for g in groups:
        for w in g:
            if w and w not in seen:
                seen.append(w)
    seen.sort(key=len, reverse=True)
    # staging_quality 字表裡含「(?:」的是正規式（例 高鐵娛樂(?:購物)?城），照原樣用；其他一律跳脫
    return '|'.join(w if '(?:' in w else re.escape(w) for w in seen)


